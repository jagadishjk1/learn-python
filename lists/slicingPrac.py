# Create a list of 10 numbers (1 through 10). Using slicing:

lis_numbers = [10, 20, 30, 40, 50, 60, 70, 80, 47, 67]

# Print the first 3 numbers
print(lis_numbers[0:3])
# Print the last 3 numbers
print(lis_numbers[-3:])
# Print every 2nd number (hint: list[start:stop:step])
print(lis_numbers[0::2])
# Print th. (hint: step can be negative)
print(lis_numbers[::-1])